void swap(int v[], int i, int j) {
    int empty; 
    empty = v[i];
    v[i] = v[j];
    v[j] = empty;
}

int ordena_array(int a[], int N) {
    for(int i = 0; i < N; i ++){
        int digits[10];
        int count = 0;
        int num = a[i];

        while (num > 0){
            int digito = num % 10;
            if (digito != 0) digits[count++] = digito;
            num /= 10;
        }
        for(int f = 0; f < count - 1; f++){
            for(int c = f + 1; c < count; c++){
                if (digits[f] > digits[c]) swap(digits, f, c);
            }
        }
        int ordenado = 0;
        for(int f = 0; f < count; f++) ordenado = ordenado * 10 + digits[f]; 
        a[i] = ordenado; 
    }
    for(int i = 1; i < N; i ++){
        for(int j = 0; j < N - i - 1; j ++){
            if (a[j] > a[j + 1]) swap(a, j, j + 1);
        }
    }
    int max_freq = 0; 
    int num_mas_freq = a[0];
    int freq_actual = 1; 
    for(int i = 1; i < N; i ++){
        if (a[i] == a[i - 1]) freq_actual++;
        else {
            if (freq_actual > max_freq) {
                max_freq = freq_actual;
                num_mas_freq = a[i - 1];
            }
            freq_actual = 1;
        }
    }
    if(freq_actual > max_freq) num_mas_freq = a[N - 1];
    return num_mas_freq;
}

